using System;
using System.Collections.Generic;
using CourtSim.Core.Decisions;

namespace CourtSim.Core.Advising
{
    /// <summary>
    /// How a deliberately flawed suggestion goes wrong. The taxonomy is what the debrief teaches and what
    /// Phase 3's adaptation targets: a trainee who misses one kind of flaw sees more of it.
    /// </summary>
    public enum FlawKind
    {
        /// <summary>Sound advice.</summary>
        None,

        /// <summary>States the wrong legal test, burden or rule.</summary>
        MisstatedLaw,

        /// <summary>Contradicts or distorts the case record.</summary>
        MisreadFact,

        /// <summary>Ignores a material consideration that changes the outcome.</summary>
        OmittedFactor,

        /// <summary>Relies on a consideration the law forbids or treats as irrelevant.</summary>
        ImproperFactor,
    }

    /// <summary>How fully a suggestion explains its reasoning.</summary>
    public enum ExplanationDetail
    {
        /// <summary>Two to four sentences.</summary>
        Standard,

        /// <summary>Walks through every factor relied on; used after a trainee rejects sound advice twice running.</summary>
        Detailed,
    }

    public enum AdviceConfidence
    {
        Low,
        Medium,
        High,
    }

    /// <summary>Where a piece of advice came from.</summary>
    public enum AdviceSource
    {
        /// <summary>Authored text from the case file (offline, or after a failed API call).</summary>
        Scripted,

        /// <summary>Generated by Claude for this case and decision point.</summary>
        Claude,

        /// <summary>Generated by a local model (Ollama) on this machine.</summary>
        LocalModel,
    }

    /// <summary>Wire names and debrief descriptions for <see cref="FlawKind"/>.</summary>
    public static class FlawKinds
    {
        public static readonly IReadOnlyList<FlawKind> All = new[]
        {
            FlawKind.MisstatedLaw,
            FlawKind.MisreadFact,
            FlawKind.OmittedFactor,
            FlawKind.ImproperFactor,
        };

        /// <summary>The snake_case name used in case files and logs.</summary>
        public static string ToWireName(FlawKind kind)
        {
            switch (kind)
            {
                case FlawKind.None:
                    return "none";
                case FlawKind.MisstatedLaw:
                    return "misstated_law";
                case FlawKind.MisreadFact:
                    return "misread_fact";
                case FlawKind.OmittedFactor:
                    return "omitted_factor";
                case FlawKind.ImproperFactor:
                    return "improper_factor";
                default:
                    throw new ArgumentOutOfRangeException(nameof(kind), kind, "Unknown flaw kind.");
            }
        }

        public static bool TryParse(string wireName, out FlawKind kind)
        {
            foreach (FlawKind candidate in new[] { FlawKind.None, FlawKind.MisstatedLaw, FlawKind.MisreadFact, FlawKind.OmittedFactor, FlawKind.ImproperFactor })
            {
                if (ToWireName(candidate) == wireName)
                {
                    kind = candidate;
                    return true;
                }
            }

            kind = FlawKind.None;
            return false;
        }

        /// <summary>Plain-language description of the flaw, used in prompts and the debrief.</summary>
        public static string Describe(FlawKind kind)
        {
            switch (kind)
            {
                case FlawKind.None:
                    return "No flaw: the advice applies the correct law to an accurate reading of the record.";
                case FlawKind.MisstatedLaw:
                    return "Misstated law: the advice applies the wrong legal test, burden or rule.";
                case FlawKind.MisreadFact:
                    return "Misread fact: the advice relies on something the record does not say.";
                case FlawKind.OmittedFactor:
                    return "Omitted factor: the advice ignores a material consideration that changes the outcome.";
                case FlawKind.ImproperFactor:
                    return "Improper factor: the advice relies on a consideration the law treats as irrelevant or forbidden.";
                default:
                    throw new ArgumentOutOfRangeException(nameof(kind), kind, "Unknown flaw kind.");
            }
        }
    }

    public static class AdviceConfidences
    {
        public static string ToWireName(AdviceConfidence confidence)
        {
            switch (confidence)
            {
                case AdviceConfidence.Low:
                    return "low";
                case AdviceConfidence.Medium:
                    return "medium";
                case AdviceConfidence.High:
                    return "high";
                default:
                    throw new ArgumentOutOfRangeException(nameof(confidence), confidence, "Unknown confidence.");
            }
        }

        public static bool TryParse(string wireName, out AdviceConfidence confidence)
        {
            switch (wireName)
            {
                case "low":
                    confidence = AdviceConfidence.Low;
                    return true;
                case "medium":
                    confidence = AdviceConfidence.Medium;
                    return true;
                case "high":
                    confidence = AdviceConfidence.High;
                    return true;
                default:
                    confidence = AdviceConfidence.Medium;
                    return false;
            }
        }
    }

    /// <summary>A suggested ruling shown to the trainee, plus the hidden truth about it used for scoring and debrief.</summary>
    public sealed class Advice
    {
        public Advice(
            DecisionPointKind kind,
            string recommendedOptionId,
            string rationale,
            IReadOnlyList<string> citedFactorIds,
            AdviceConfidence confidence,
            FlawKind flaw,
            string flawExplanation,
            AdviceSource source)
        {
            if (string.IsNullOrEmpty(recommendedOptionId))
            {
                throw new ArgumentException("Advice must recommend an option.", nameof(recommendedOptionId));
            }

            Kind = kind;
            RecommendedOptionId = recommendedOptionId;
            Rationale = rationale ?? string.Empty;
            CitedFactorIds = citedFactorIds ?? Array.Empty<string>();
            Confidence = confidence;
            Flaw = flaw;
            FlawExplanation = flawExplanation ?? string.Empty;
            Source = source;
        }

        public DecisionPointKind Kind { get; }

        public string RecommendedOptionId { get; }

        /// <summary>What the trainee reads. Never mentions the flaw.</summary>
        public string Rationale { get; }

        public IReadOnlyList<string> CitedFactorIds { get; }

        public AdviceConfidence Confidence { get; }

        /// <summary>Hidden until the debrief.</summary>
        public FlawKind Flaw { get; }

        public bool IsFlawed => Flaw != FlawKind.None;

        /// <summary>Hidden until the debrief. Empty for sound advice.</summary>
        public string FlawExplanation { get; }

        public AdviceSource Source { get; }
    }
}
